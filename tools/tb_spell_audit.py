# Turn based spell audit (tier 1, no game needed): reads every PST spell and writes
#   dev/spell_manifest.json   what tb_spell_suite.ps1 casts and checks
#   dev/spell_audit.md        the timing cases turn based combat has to handle, per spell
# Run: python tools/tb_spell_audit.py
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from tb_gamedata import GameData, spell_number, TIMING, REPO

ROUND_TICKS = 75 # pst: 5 second rounds, 15 ticks a second
DELAYED = (3, 4, 5)
SEMANTIC = {12: "damage", 13: "death", 17: "heal", 24: "fear", 39: "sleep", 74: "blind", 109: "hold", 128: "confuse",
	0: "ac", 54: "tohit", 130: "bless", 203: "curse", 33: "save", 34: "save", 35: "save", 36: "save", 37: "save"}
# PST timing 0 stored seconds, the delayed ones ticks (EffectQueue::ApplyEffect)
def ticks(fx):
	return fx["duration"] * 15 if fx["timing"] == 0 else fx["duration"]

def audit(gd):
	spells = []
	for name in gd.names("spl"):
		s = gd.spell(name)
		if not s or not s["name"] or not s["headers"]:
			continue
		num = spell_number(name)
		h = s["headers"][-1] # the strongest header: the suite casts at level 12+
		pro = h["projectile"]
		delays = sorted({fx["duration"] for fx in h["effects"] if fx["timing"] in DELAYED})
		durations = sorted({ticks(fx) for fx in h["effects"] if fx["timing"] in (0, 10) and fx["duration"]})
		flags = []
		if pro and pro[1] == "missing":
			flags.append("projectile %s missing" % pro[0])
		if pro and pro[1] == "area" and pro[4] > 1:
			flags.append("repeating area: %d pulses every %d ticks" % (pro[4], pro[3]))
		if pro and pro[1] == "area" and pro[3] >= ROUND_TICKS:
			flags.append("area waits %d ticks before it goes off" % pro[3])
		if pro and pro[1] == "area" and pro[2] == 0:
			flags.append("area with explosion radius 0")
		if delays and delays[-1] >= ROUND_TICKS:
			flags.append("onset delay %d ticks (>= a round)" % delays[-1])
		odd = [d for d in durations if d >= ROUND_TICKS and d % ROUND_TICKS]
		if odd:
			flags.append("durations not whole rounds: %s" % ", ".join("%d (%.1f rd)" % (d, d / ROUND_TICKS) for d in odd))
		short = [d for d in durations if d < ROUND_TICKS]
		kinds = sorted({SEMANTIC[fx["op"]] for fx in h["effects"] if fx["op"] in SEMANTIC})
		spells.append({
			"resref": name, "number": num, "name": s["name"], "level": s["level"], "type": s["type"],
			"duration_text": s["duration_text"], "target": h["target"], "range": h["range"],
			"projectile": pro, "delays": delays, "durations": durations, "short_durations": short,
			"kinds": kinds, "flags": flags,
			"effects": [(fx["op"], TIMING.get(fx["timing"], fx["timing"]), fx["duration"], fx["res"]) for fx in h["effects"]],
		})
	return spells

def write(spells):
	dev = os.path.join(REPO, "dev")
	os.makedirs(dev, exist_ok=True)
	with open(os.path.join(dev, "spell_manifest.json"), "w", encoding="utf-8") as f:
		json.dump(spells, f, indent=1)
	lines = ["# Turn based spell audit", "",
		"Generated by `tools/tb_spell_audit.py` from the game data. Rounds are 75 ticks (5 seconds).",
		"Target: 1 creature, 4 area/point, 5 caster. Delays and durations in ticks.", "",
		"| Spell | # | Duration (description) | Target | Projectile | Delays | Durations | Flags |",
		"|---|---|---|---|---|---|---|---|"]
	for s in spells:
		pro = s["projectile"]
		pdesc = "" if not pro else ("%s %s" % (pro[0], pro[1]) + (" r%d" % pro[2] if pro[1] == "area" else ""))
		lines.append("| %s %s | %s | %s | %d | %s | %s | %s | %s |" % (s["resref"], s["name"], s["number"] or "", s["duration_text"],
			s["target"], pdesc, ",".join(map(str, s["delays"])), ",".join(map(str, s["durations"])), "; ".join(s["flags"])))
	counts = {}
	for s in spells:
		for fl in s["flags"]:
			key = fl.split(":")[0].split(" (")[0]
			key = "onset delay >= a round" if key.startswith("onset delay") else key
			key = "projectile missing" if key.startswith("projectile ") else key
			key = "area waits before it goes off" if key.startswith("area waits") else key
			counts[key] = counts.get(key, 0) + 1
	lines += ["", "## Flag counts", ""] + ["- %s: %d" % (k, v) for k, v in sorted(counts.items())]
	with open(os.path.join(dev, "spell_audit.md"), "w", encoding="utf-8") as f:
		f.write("\n".join(lines) + "\n")
	return counts

if __name__ == "__main__":
	spells = audit(GameData())
	counts = write(spells)
	print("%d spells; flags: %s" % (len(spells), counts))
